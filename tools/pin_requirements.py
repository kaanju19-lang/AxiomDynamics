"""
Pin dependency versions to the hashes the package index actually serves.

D09 §4.4 disclosed "no hash pinning of dependencies" as a gap, target Q1 2027.
This is the tool that closes it. It exists because of a specific failure the
project has already made once: **a digest typed by a human is a digest nobody
verified.** Writing invented hashes into `requirements.txt` makes the file look
pinned while `pip install --require-hashes` rejects every real download — a
control that fails at exactly the moment it is needed.

So the rule this tool enforces is: **it never writes a hash it did not observe in
the same run, from a file it downloaded itself.** There is no `--hash` flag to
paste one in, and there is no way to write the file without the download having
succeeded.

Where it has to run: a machine with network access to PyPI. The sandbox that
builds the Platform cannot reach an index (the proxy returns 403), so the pin
step is a release-host step — the same place C01 Part C2 already prepares the
sealed archive. That is not a limitation of this tool; it is a fact about which
machine is allowed to decide what a release contains.

Usage:
    # show what the index serves for each requirement, change nothing
    python3 -I tools/pin_requirements.py --check

    # rewrite requirements.txt with the observed hashes (writes a .bak beside it)
    python3 -I tools/pin_requirements.py --write

    # verify an already-pinned file downloads and matches, touching nothing
    python3 -I tools/pin_requirements.py --verify

Exit codes: 0 ok, 1 a mismatch or an offline failure, 2 bad usage.
"""

from __future__ import annotations

import argparse
import hashlib
import os
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_REQ = os.path.join(ROOT, "requirements.txt")
CHUNK = 1 << 20

PREAMBLE = """\
# Only dependency. Everything else (HTTP server, JSON, etc.) is Python stdlib,
# by design -- this app is meant to run on an air-gapped edge box with no
# pip install step beyond this.
#
# HASH-PINNED, generated by tools/pin_requirements.py. D09 §4.4 disclosed "no
# hash pinning of dependencies" as a gap; this closes it. The hashes below are
# the digests the index served for this exact version, observed when this file
# was generated, not typed by hand. `pip install --require-hashes` refuses a
# substituted file even when the version string matches, which is what version
# pinning alone cannot do.
#
# TO UPDATE: bump the version, then run
#     python3 -I tools/pin_requirements.py --write
# on a host with index access, and commit the result. The release host is the
# only machine allowed to decide what a release contains.
"""


def _sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(CHUNK), b""):
            h.update(chunk)
    return h.hexdigest()


def _parse(path):
    """Return [(name, version, comment_block_lines)] and the trailing comment."""
    reqs, comments = [], []
    with open(path, encoding="utf-8") as fh:
        for raw in fh:
            line = raw.rstrip("\n")
            s = line.split("#", 1)[0].strip()
            if not s:
                if line.strip():
                    comments.append(line)
                continue
            if s.startswith("-"):
                continue
            name, _, rest = s.partition("==")
            version = rest.strip().split()[0] if rest.strip() else ""
            reqs.append((name.strip(), version))
    return reqs


def _download(name, version, dest):
    """
    Download the distributions for one requirement and return their digests.

    `--no-deps` because a transitive dependency's hashes belong to that
    dependency's own requirement line, not this one. `--no-binary :all:` is NOT
    used: we want exactly what pip would install, which is usually a wheel, and
    the hash of the wheel is what `--require-hashes` compares against.
    """
    cmd = [sys.executable, "-m", "pip", "download",
           "%s==%s" % (name, version), "-d", dest, "--no-deps", "--quiet"]
    p = subprocess.run(cmd, capture_output=True, text=True)
    if p.returncode != 0:
        raise RuntimeError(
            "could not download %s==%s — this tool needs index access and "
            "cannot generate a hash it did not observe.\n%s"
            % (name, version, (p.stderr or p.stdout).strip()))

    digests, files = [], []
    for fn in sorted(os.listdir(dest)):
        full = os.path.join(dest, fn)
        if not os.path.isfile(full):
            continue
        digests.append(_sha256(full))
        files.append(fn)
    if not digests:
        raise RuntimeError("pip downloaded nothing for %s==%s" % (name, version))
    return digests, files


def _observed(req_path, reqs):
    """[(name, version, [digests], [filenames])] — observed, never invented."""
    out = []
    for name, version in reqs:
        if not version or version.startswith(">") or version.startswith("<"):
            raise RuntimeError(
                "%r is not pinned to an exact version (%r). Hash pinning "
                "requires '=='. A range cannot be hashed because the index may "
                "serve any matching file." % (name, version))
        d = tempfile.mkdtemp(prefix="axiom-pin-")
        try:
            digests, files = _download(name, version, d)
        finally:
            shutil.rmtree(d, ignore_errors=True)
        out.append((name, version, digests, files))
    return out


def _render(observed):
    lines = [PREAMBLE.rstrip("\n")]
    for name, version, digests, files in observed:
        lines.append("")
        lines.append("# %s: %s" % (name, ", ".join(files)))
        lines.append("%s==%s \\" % (name, version))
        for i, dg in enumerate(digests):
            sep = " \\" if i < len(digests) - 1 else ""
            lines.append("    --hash=sha256:%s%s" % (dg, sep))
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(
        description="Pin requirements to observed index hashes.")
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--check", action="store_true",
                   help="report the hashes the index serves; write nothing")
    g.add_argument("--write", action="store_true",
                   help="rewrite the requirements file with observed hashes")
    g.add_argument("--verify", action="store_true",
                   help="download and confirm an already-pinned file matches")
    ap.add_argument("--requirements", default=DEFAULT_REQ)
    a = ap.parse_args(argv)

    if not os.path.isfile(a.requirements):
        print("no such file: %s" % a.requirements)
        return 2

    reqs = _parse(a.requirements)
    if not reqs:
        print("no requirements found in %s" % a.requirements)
        return 2

    try:
        observed = _observed(a.requirements, reqs)
    except RuntimeError as exc:
        print("FAILED: %s" % exc)
        return 1

    if a.check:
        for name, version, digests, files in observed:
            print("%s==%s" % (name, version))
            for fn, dg in zip(files, digests):
                print("    %-42s sha256:%s" % (fn, dg))
        print("\nNothing written. Re-run with --write to pin these.")
        return 0

    if a.verify:
        # Read the hashes already in the file (not the ones we just fetched) and
        # require them to be a superset of what the index now serves. A pinned
        # file whose hash no longer matches means the index changed the
        # artefact, which is the event the control exists to catch.
        pinned = set()
        with open(a.requirements, encoding="utf-8") as fh:
            for line in fh:
                if "--hash=sha256:" in line:
                    pinned.add(line.split("--hash=sha256:", 1)[1]
                               .strip().rstrip("\\").strip())
        served = {d for _, _, ds, _ in observed for d in ds}
        missing = served - pinned
        if missing:
            print("MISMATCH: the index served %d hash(es) not pinned in %s"
                  % (len(missing), a.requirements))
            for m in sorted(missing):
                print("    sha256:%s" % m)
            return 1
        print("ok — every file the index served is pinned (%d hash(es))"
              % len(served))
        return 0

    backup = a.requirements + ".bak"
    shutil.copy2(a.requirements, backup)
    with open(a.requirements, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(_render(observed))
    print("wrote %s (%d requirement(s)); previous file at %s"
          % (a.requirements, len(observed), os.path.basename(backup)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
