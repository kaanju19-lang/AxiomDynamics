"""
Tests for tools/pin_requirements.py (D09 §4.4 hash pinning).

The failure this suite is written against is not "the tool crashes". It is the
one that nearly shipped: **a digest written by a human, or by a model, into a
file that therefore looks pinned and is not.** `pip install --require-hashes`
rejects a wrong hash, so the control fails closed — but it fails at release time,
on the Railroad's machine, after the artefact was shipped. The tests below pin
down that the tool can only ever write a hash it observed in the same run.

Nothing here touches the network. The download step is exercised with fakes,
because a suite that needs PyPI to run is a suite that does not run on the
air-gapped box this product is built for.

Run: python3 -I tests/test_pin_requirements.py
"""

import importlib.util
import os
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

TOOL = os.path.join(ROOT, "tools", "pin_requirements.py")
spec = importlib.util.spec_from_file_location("pin_requirements", TOOL)
pin = importlib.util.module_from_spec(spec)
spec.loader.exec_module(pin)

RESULTS = []


def test(fn):
    try:
        fn()
    except AssertionError as exc:
        RESULTS.append((fn.__name__, False, exc))
    except Exception as exc:  # noqa: BLE001
        RESULTS.append((fn.__name__, False, "%s: %s" % (type(exc).__name__, exc)))
    else:
        RESULTS.append((fn.__name__, True, None))
    return fn


TMP = tempfile.mkdtemp(prefix="axiom-pin-test-")

# Helpers defined before any @test decorator runs: the decorator CALLS the
# function at definition time, so a helper defined further down the file does
# not exist yet when the first test that uses it fires.


def reqfile(body, name="requirements.txt"):
    p = os.path.join(TMP, name)
    with open(p, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(body)
    return p


def _stub_observed(observed):
    """Replace the network step with a fixed observation."""
    real = pin._observed
    pin._observed = lambda path, reqs: observed
    pin._real_observed = real


def _restore_observed():
    if hasattr(pin, "_real_observed"):
        pin._observed = pin._real_observed
        del pin._real_observed


def _fake_observed(files):
    """Exercise the guard inside _download without a network."""
    real = pin.subprocess.run

    class R:
        returncode = 0
        stdout = stderr = ""

    def fake(cmd, **kw):
        dest = cmd[cmd.index("-d") + 1]
        for fn, content in files:
            with open(os.path.join(dest, fn), "wb") as fh:
                fh.write(content)
        return R()

    pin.subprocess.run = fake
    try:
        d = tempfile.mkdtemp(prefix="axiom-pin-fake-")
        return pin._download("numpy", "2.2.6", d)
    finally:
        pin.subprocess.run = real


# ---------------------------------------------------------------------------
# Parsing
# ---------------------------------------------------------------------------
@test
def test_a_range_is_refused_because_it_cannot_be_hashed():
    """
    The important one. `numpy>=1.26` cannot be hash-pinned: the index may serve
    any matching file tomorrow. A tool that quietly accepted it would emit a
    requirements file with a range and no hashes and call it pinned.
    """
    p = reqfile("numpy>=1.26\n")
    try:
        pin._observed(p, pin._parse(p))
    except RuntimeError as exc:
        assert "not pinned to an exact version" in str(exc), exc
    else:
        raise AssertionError("a range must not be accepted for hashing")


@test
def test_comments_and_blank_lines_do_not_become_requirements():
    p = reqfile("# a comment\n\nnumpy==2.2.6  # inline\nother==1.0\n")
    reqs = pin._parse(p)
    assert [r[0] for r in reqs] == ["numpy", "other"], reqs
    assert [r[1] for r in reqs] == ["2.2.6", "1.0"], reqs


# ---------------------------------------------------------------------------
# The render, and what it must not be able to contain
# ---------------------------------------------------------------------------
@test
def test_the_rendered_file_contains_only_observed_hashes():
    observed = [("numpy", "2.2.6", ["a" * 64, "b" * 64],
                 ["numpy-2.2.6-cp311.whl", "numpy-2.2.6.tar.gz"])]
    out = pin._render(observed)
    assert out.count("--hash=sha256:") == 2, out
    assert "a" * 64 in out and "b" * 64 in out
    assert "numpy==2.2.6" in out
    # The preamble has to say where the numbers came from, or a reader cannot
    # tell a generated file from a hand-edited one. Asserted in pieces rather
    # than as one sentence: comment prose is hard-wrapped, so any phrase long
    # enough to be meaningful gets a "#" inserted into the middle of it.
    folded = " ".join(out.split())
    assert "generated by tools/pin_requirements.py" in folded, out
    assert "not typed by hand" in folded, out
    assert "--require-hashes" in folded, out


@test
def test_the_rendered_file_is_valid_continuation_syntax():
    """pip's hash lines use trailing backslashes; a missing one truncates it."""
    observed = [("numpy", "2.2.6", ["a" * 64, "b" * 64], ["w.whl", "s.tar.gz"])]
    out = pin._render(observed)
    lines = [l for l in out.splitlines() if l.strip()]
    hash_lines = [l for l in lines if "--hash=sha256:" in l]
    assert len(hash_lines) == 2
    assert hash_lines[0].rstrip().endswith("\\"), hash_lines[0]
    assert not hash_lines[1].rstrip().endswith("\\"), hash_lines[1]


@test
def test_an_empty_download_is_an_error_not_an_empty_pin():
    """
    `pip download` exiting 0 and leaving nothing should not produce a
    requirements file that pins a package to zero hashes.
    """
    try:
        _fake_observed([])
    except RuntimeError as exc:
        assert "downloaded nothing" in str(exc), exc
    else:
        raise AssertionError("an empty download must raise")



@test
def test_a_successful_download_returns_a_digest_per_file():
    digests, files = _fake_observed([("numpy-2.2.6.whl", b"wheel-bytes"),
                                     ("numpy-2.2.6.tar.gz", b"sdist-bytes")])
    assert len(digests) == 2 and len(files) == 2, (digests, files)
    assert all(len(d) == 64 for d in digests), digests
    import hashlib
    assert hashlib.sha256(b"wheel-bytes").hexdigest() in digests


@test
def test_a_failed_download_raises_rather_than_returning_nothing():
    real = pin.subprocess.run

    class R:
        returncode = 1
        stdout = ""
        stderr = "ERROR: No matching distribution found"

    pin.subprocess.run = lambda cmd, **kw: R()
    try:
        d = tempfile.mkdtemp(prefix="axiom-pin-fail-")
        try:
            pin._download("numpy", "9.9.9", d)
        except RuntimeError as exc:
            assert "cannot generate a hash it did not observe" in str(exc), exc
        else:
            raise AssertionError("a failed download must raise")
    finally:
        pin.subprocess.run = real


# ---------------------------------------------------------------------------
# verify
# ---------------------------------------------------------------------------
@test
def test_verify_reports_a_hash_the_index_serves_but_the_file_does_not_pin():
    p = reqfile("numpy==2.2.6 \\\n    --hash=sha256:%s\n" % ("a" * 64))
    _stub_observed([("numpy", "2.2.6", ["a" * 64, "c" * 64], ["w", "s"])])
    try:
        rc = pin.main(["--verify", "--requirements", p])
    finally:
        _restore_observed()
    assert rc == 1, "a served hash absent from the file must fail verification"


@test
def test_verify_passes_when_every_served_hash_is_pinned():
    p = reqfile("numpy==2.2.6 \\\n    --hash=sha256:%s \\\n    --hash=sha256:%s\n"
                % ("a" * 64, "b" * 64))
    _stub_observed([("numpy", "2.2.6", ["a" * 64, "b" * 64], ["w", "s"])])
    try:
        rc = pin.main(["--verify", "--requirements", p])
    finally:
        _restore_observed()
    assert rc == 0, "every served hash is pinned; verify must pass"


# ---------------------------------------------------------------------------
# The defect this suite was written after
# ---------------------------------------------------------------------------
@test
def test_no_hash_anywhere_in_this_tool_was_typed_by_a_human():
    """
    Regression test for a mistake made while building this: two invented
    SHA-256 strings were written into requirements.txt, which would have made
    `pip install --require-hashes` reject every real numpy download.

    The property: the tool has no literal 64-hex-char string in it. A digest
    can only enter the output through `_sha256` of a downloaded file.
    """
    import re
    src = open(TOOL, encoding="utf-8").read()
    literals = re.findall(r"[0-9a-fA-F]{64}", src)
    assert not literals, (
        "a 64-hex literal appears in the tool; hashes must be observed, not "
        "written: %r" % literals)


@test
def test_this_file_does_not_contain_a_real_digest_either():
    import re
    src = open(os.path.abspath(__file__), encoding="utf-8").read()
    # The fake digests above are all one repeated character, which cannot be a
    # real SHA-256 of anything meaningful to us. Anything else is a smell.
    real = [m for m in re.findall(r"[0-9a-fA-F]{64}", src)
            if len(set(m.lower())) > 2]
    assert not real, real


@test
def test_requirements_txt_pins_numpy_only_after_the_release_host_runs():
    """
    The repository's requirements.txt is a RANGE today and that is correct: the
    pin step runs on a host with index access. This test records the current
    state so that a later session cannot read "hash pinning built" as "the file
    is pinned" without checking.
    """
    p = os.path.join(ROOT, "requirements.txt")
    body = open(p, encoding="utf-8").read()
    reqs = [l for l in body.splitlines()
            if l.strip() and not l.strip().startswith("#")]
    pinned = any("--hash=sha256:" in l for l in reqs)
    exact = any(l.strip().startswith("numpy==") for l in reqs)
    if pinned:
        assert exact, "a hash without an exact version is not a pin"
        assert "tools/pin_requirements.py" in body, (
            "a pinned file must say how it was generated, or a reader cannot "
            "tell it from a hand-edited one")
    else:
        assert any("numpy>=" in l or "numpy==" in l for l in reqs), reqs


# ---------------------------------------------------------------------------
def main():
    print(f"{len(RESULTS)} tests")
    bad = 0
    for name, ok, exc in RESULTS:
        print(("PASS  " if ok else "FAIL  ") + name + ("" if ok else f" -> {exc!r}"))
        bad += 0 if ok else 1
    print(f"\n{len(RESULTS) - bad} passed, {bad} failed")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
